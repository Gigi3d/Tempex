#!/usr/bin/env bash
# Regenerate the TempexEscrow ABI consumed by packages/sdk.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p packages/sdk/src/abi
{
  echo "// Generated by scripts/gen-abi.sh — do not edit by hand."
  echo "export const tempexEscrowAbi = $(forge inspect TempexEscrow abi --root contracts --json) as const;"
} > packages/sdk/src/abi/TempexEscrow.ts
echo "wrote packages/sdk/src/abi/TempexEscrow.ts"
